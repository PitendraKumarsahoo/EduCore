export function hasModulePermission(
  role: RoleKey | undefined,
  module: ModuleKey,
  action: PermissionAction = 'view',
  customMatrix?: ModulePermissionMap,
  memberOverrides?: ModulePermissionMap,
): boolean {
  if (!role) return false;
  if (role === 'super_admin' || role === 'institution_admin') return true;
  const memberActions = memberOverrides?.[module];
  if (memberActions) return memberActions.includes(action);
  const roleActions = customMatrix?.[module] ?? DEFAULT_ROLE_PERMISSIONS[role]?.[module];
  return Boolean(roleActions && roleActions.includes(action));
}
